import { prisma } from './prisma';
import { LOG_SOURCES } from './log-events';
import { loadRuleTelemetry, loadTelemetryInfo, telemetrySource } from './coverage-analysis';
import { generateUniqueSlug } from './slug';
import { syncDerivedLinks } from './derived-links';

// Data source pages for the log sources the rules read but no data source page
// describes yet. A generated page lists the events rules use and is linked to
// them (manual links, kept when the page is edited), so impact analysis can
// answer "what if we stop collecting this source?" and the detection chain
// ends in a data source. The collection details are left for people to fill.

export interface DataSourcePlan {
  source: string;
  label: string;
  platform: string;
  /** Active rules reading the source */
  rules: number;
  events: { key: string; label: string; rules: number }[];
  /** Data source pages already linked to the source's events */
  pages: { title: string; slug: string }[];
}

/** Every log source active rules read, with the data source pages that cover it. */
export async function planDataSourcePages(): Promise<DataSourcePlan[]> {
  const [rules, info, dsPages] = await Promise.all([
    loadRuleTelemetry(),
    loadTelemetryInfo(),
    prisma.page.findMany({
      where: { type: 'DATA_SOURCE' },
      select: {
        title: true,
        slug: true,
        sysmonEvents: { select: { sysmonEvent: { select: { eventId: true } } } },
        logEvents: { select: { logEvent: { select: { key: true } } } },
      },
    }),
  ]);
  const bySource = new Map<string, { rules: Set<number>; events: Map<string, Set<number>> }>();
  for (const r of rules) {
    if (r.status === 'deprecated') continue;
    for (const key of r.telemetry) {
      const source = telemetrySource(key);
      // Names DetectKB couldn't place are not one source
      if (source === 'other') continue;
      if (!bySource.has(source)) bySource.set(source, { rules: new Set(), events: new Map() });
      const s = bySource.get(source)!;
      s.rules.add(r.pageId);
      if (!s.events.has(key)) s.events.set(key, new Set());
      s.events.get(key)!.add(r.pageId);
    }
  }
  const pagesBySource = new Map<string, { title: string; slug: string }[]>();
  for (const p of dsPages) {
    const keys = [...p.sysmonEvents.map((e) => `sysmon:${e.sysmonEvent.eventId}`), ...p.logEvents.map((e) => e.logEvent.key)];
    for (const source of new Set(keys.map(telemetrySource))) pagesBySource.set(source, [...(pagesBySource.get(source) ?? []), { title: p.title, slug: p.slug }]);
  }
  return Array.from(bySource, ([source, s]) => {
    const first = info.get(Array.from(s.events.keys())[0]);
    return {
      source,
      label: source === 'sysmon' ? 'Sysmon' : LOG_SOURCES[source]?.label ?? first?.sourceLabel ?? source,
      platform: source === 'sysmon' ? 'Windows' : LOG_SOURCES[source]?.platform ?? (source.startsWith('windows-') ? 'Windows' : 'Other'),
      rules: s.rules.size,
      events: Array.from(s.events, ([key, pages]) => ({ key, label: info.get(key)?.label ?? key, rules: pages.size })).sort(
        (a, b) => b.rules - a.rules || a.key.localeCompare(b.key)
      ),
      pages: pagesBySource.get(source) ?? [],
    };
  }).sort((a, b) => Number(a.pages.length > 0) - Number(b.pages.length > 0) || b.rules - a.rules);
}

/** The generated page text. */
export function dataSourceContent(plan: Pick<DataSourcePlan, 'label' | 'platform' | 'rules' | 'events'>): string {
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  return [
    `Telemetry from **${plan.label}** (${plan.platform}). ${plan.rules} active rule${plan.rules === 1 ? ' reads' : 's read'} it.`,
    '',
    '_Generated by DetectKB from the rules that read this source. Describe how it is collected in your environment below; the event links stay when you edit the page._',
    '',
    '## Collection',
    '',
    '- **Where it is collected:** (index / sourcetype, or the SIEM table)',
    '- **Hosts / coverage:** (which systems send it, and how many)',
    '- **Retention:** ',
    '- **Owner:** (team to call when it stops arriving)',
    '',
    '## Events used by rules',
    '',
    // Count first: a row starting with a source name would be read as an event name
    '| Rules | Event |',
    '|---:|---|',
    ...plan.events.map((e) => `| ${e.rules} | ${cell(e.label)} |`),
    '',
  ].join('\n');
}

/** Creates a data source page for each of the given sources that has none yet. */
export async function createDataSourcePages(sources: string[]) {
  const plans = (await planDataSourcePages()).filter((p) => sources.includes(p.source) && !p.pages.length);
  const created: { source: string; title: string; slug: string }[] = [];
  for (const plan of plans) {
    const title = plan.source === 'sysmon' ? 'Sysmon' : plan.label;
    const page = await prisma.page.create({
      data: { title, slug: await generateUniqueSlug(title), type: 'DATA_SOURCE', contentMd: dataSourceContent(plan) },
      select: { id: true, title: true, slug: true },
    });
    const sysmonIds = plan.events.filter((e) => e.key.startsWith('sysmon:')).map((e) => Number(e.key.slice(7)));
    if (sysmonIds.length) {
      const events = await prisma.sysmonEvent.findMany({ where: { eventId: { in: sysmonIds } }, select: { id: true } });
      await prisma.pageSysmonEvent.createMany({ data: events.map((e) => ({ pageId: page.id, sysmonEventId: e.id, source: 'manual', basis: 'manual' })), skipDuplicates: true });
    }
    const logKeys = plan.events.filter((e) => !e.key.startsWith('sysmon:')).map((e) => e.key);
    if (logKeys.length) {
      const events = await prisma.logEvent.findMany({ where: { key: { in: logKeys } }, select: { id: true } });
      await prisma.pageLogEvent.createMany({ data: events.map((e) => ({ pageId: page.id, logEventId: e.id, source: 'manual', basis: 'declared' })), skipDuplicates: true });
    }
    await syncDerivedLinks(page.id);
    created.push({ source: plan.source, title: page.title, slug: page.slug });
  }
  return created;
}
